#!/usr/bin/env bash
# Install the rescue demo's external dependencies OUTSIDE the repository.
#
# Creates a virtual environment (default ~/venvs/rescue) with the pinned
# packages of requirements.txt (numpy, pyzmq, pytest) and the wrapper
# interpreter `<venv>/bin/rescue-python` every script of the demo is run with.
#
# --isaac also installs NVIDIA Isaac Sim (ISAAC_VERSION, default 6.2.0.0) from
# pypi.nvidia.com; it is used only by isaac_world.py. Installing it means
# accepting the NVIDIA Isaac Sim EULA: the script refuses unless the user sets
# OMNI_KIT_ACCEPT_EULA=YES, and the wrapper then exports it. On a host without
# system packages (no root), three user-space pieces go to <venv>-syslibs,
# fetched with `apt-get download` (no root) and unpacked with `dpkg-deb -x`:
#   - the Python 3.12 headers: psutil and PyOpenGL-accelerate have no aarch64
#     wheels and build from source;
#   - X11/GL client libraries: the NVIDIA Vulkan ICD links libX11/libXext, and
#     without them Isaac starts but cannot create its GPU device;
# and the wrapper preloads libgomp, without which Kit exits at start-up.
# Nothing is installed system-wide.
#
# Usage: bash examples/multi_robot_rescue/setup-external.sh [--isaac] [venv_dir]
set -euo pipefail

isaac=0
if [[ "${1:-}" == "--isaac" ]]; then isaac=1; shift; fi
venv="${1:-${RESCUE_VENV:-${HOME}/venvs/rescue}}"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
isaac_version="${ISAAC_VERSION:-6.2.0.0}"
syslibs="${venv}-syslibs"
arch_dir="$(uname -m)-linux-gnu"

unpack_debs()
{
  mkdir -p "${syslibs}/debs" "${syslibs}/root"
  (cd "${syslibs}/debs" && apt-get download "$@" >/dev/null)
  for deb in "${syslibs}"/debs/*.deb; do dpkg-deb -x "${deb}" "${syslibs}/root"; done
}

if [[ ! -x "${venv}/bin/python" ]]; then
  python3.12 -m venv "${venv}"
fi
"${venv}/bin/pip" install --quiet --upgrade pip

preload=""
lib_dir=""
if [[ "${isaac}" == 1 ]]; then
  [[ "${OMNI_KIT_ACCEPT_EULA:-}" == YES ]] || {
    echo "error: Isaac Sim needs the NVIDIA EULA accepted: rerun with OMNI_KIT_ACCEPT_EULA=YES" >&2; exit 2; }
  include="$("${venv}/bin/python" -c 'import sysconfig; print(sysconfig.get_paths()["include"])')"
  cflags=""
  if [[ ! -f "${include}/Python.h" ]]; then
    unpack_debs libpython3.12-dev
    cflags="-I${syslibs}/root/usr/include/python3.12 -I${syslibs}/root/usr/include/${arch_dir}/python3.12"
  fi
  CFLAGS="${cflags}" "${venv}/bin/pip" install --quiet "isaacsim[all,extscache]==${isaac_version}" \
    --extra-index-url https://pypi.nvidia.com
  if ! ldconfig -p | grep -q 'libX11.so.6 '; then
    unpack_debs libx11-6 libxext6 libxrender1 libxrandr2 libxi6 libxfixes3 libxcursor1 libxinerama1 \
      libxt6t64 libsm6 libice6 libxcb1 libxau6 libxdmcp6 libbsd0 libmd0 libuuid1 \
      libgl1 libglx0 libglvnd0 libegl1 libopengl0 libglu1-mesa
    lib_dir="${syslibs}/root/usr/lib/${arch_dir}"
  fi
  preload="/lib/${arch_dir}/libgomp.so.1"
  [[ -f "${preload}" ]] || { unpack_debs libgomp1; preload="${syslibs}/root/usr/lib/${arch_dir}/libgomp.so.1"; }
fi
"${venv}/bin/pip" install --quiet -r "${here}/requirements.txt"

cat >"${venv}/bin/rescue-python" <<EOF
#!/usr/bin/env bash
# Generated by examples/multi_robot_rescue/setup-external.sh
${preload:+export OMNI_KIT_ACCEPT_EULA=YES    # accepted by the user at install time (--isaac)}
${preload:+export LD_PRELOAD="${preload}\${LD_PRELOAD:+:\${LD_PRELOAD}}"}
${lib_dir:+export LD_LIBRARY_PATH="${lib_dir}\${LD_LIBRARY_PATH:+:\${LD_LIBRARY_PATH}}"}
exec "${venv}/bin/python" "\$@"
EOF
chmod +x "${venv}/bin/rescue-python"

"${venv}/bin/rescue-python" -c 'import numpy, zmq; print("numpy", numpy.__version__, "pyzmq", zmq.__version__)'
if [[ "${isaac}" == 1 ]]; then
  "${venv}/bin/rescue-python" -c 'import importlib.metadata as m; print("isaacsim", m.version("isaacsim"))'
fi
echo "RESCUE_PYTHON=${venv}/bin/rescue-python"
