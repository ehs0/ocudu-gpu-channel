#!/usr/bin/env bash
# Install the V2X demo's external dependencies OUTSIDE the repository.
#
# Creates a virtual environment (default ~/venvs/v2x) with the pinned
# packages of requirements.txt — Eclipse SUMO 1.28.0 (sumo, netconvert,
# libsumo, sumolib) plus pyzmq, numpy, matplotlib, pytest — and the wrapper
# interpreter `<venv>/bin/v2x-python` every script of the demo is run with.
#
# The eclipse-sumo wheel links libX11/libXext/libXrender/libGL even when no GUI
# is used. If the host lacks them, they are fetched with `apt-get download`
# (no root) and unpacked under <venv>/x11-libs; the wrapper puts that
# directory on LD_LIBRARY_PATH. Nothing is installed system-wide.
#
# Usage: bash examples/v2x_intersection/setup-external.sh [venv_dir]
set -euo pipefail

venv="${1:-${V2X_VENV:-${HOME}/venvs/v2x}}"
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

if [[ ! -x "${venv}/bin/python" ]]; then
  python3 -m venv "${venv}"
fi
"${venv}/bin/pip" install --quiet --upgrade pip
"${venv}/bin/pip" install --quiet -r "${here}/requirements.txt"

sumo_bin="$("${venv}/bin/python" -c 'import sumo, pathlib; print(pathlib.Path(sumo.SUMO_HOME) / "bin")')"
lib_dir=""
if ldd "${sumo_bin}/sumo" | grep -q "not found"; then
  x11="${venv}/x11-libs"
  mkdir -p "${x11}/debs"
  (cd "${x11}/debs" && apt-get download libx11-6 libxext6 libxrender1 libgl1 libglvnd0 libglx0 \
      libxcb1 libxau6 libxdmcp6 libbsd0 libmd0 >/dev/null)
  for deb in "${x11}"/debs/*.deb; do dpkg-deb -x "${deb}" "${x11}/root"; done
  lib_dir="$(dirname "$(find "${x11}/root" -name 'libX11.so.6' | head -n 1)")"
  if LD_LIBRARY_PATH="${lib_dir}" ldd "${sumo_bin}/sumo" | grep "not found"; then
    echo "error: SUMO still misses shared libraries (listed above)" >&2
    exit 1
  fi
fi

cat >"${venv}/bin/v2x-python" <<EOF
#!/usr/bin/env bash
# Generated by examples/v2x_intersection/setup-external.sh
export SUMO_HOME="$(dirname "${sumo_bin}")"
export PATH="${sumo_bin}:\${PATH}"
${lib_dir:+export LD_LIBRARY_PATH="${lib_dir}\${LD_LIBRARY_PATH:+:\${LD_LIBRARY_PATH}}"}
exec "${venv}/bin/python" "\$@"
EOF
chmod +x "${venv}/bin/v2x-python"

"${venv}/bin/v2x-python" -c 'import libsumo, sumolib; print("libsumo", libsumo.getVersion()[1])'
echo "V2X_PYTHON=${venv}/bin/v2x-python"
