#!/usr/bin/env python3
"""Generate the V2X intersection scene and its two scenarios from layout.py.

    python3 build_v2x_intersection.py      # scene.xml + meshes/ + manifest.json here,
                                           # ../../scenarios/v2x_intersection/*.json

The geometry is `examples/v2x_intersection/layout.py`, the same module the
SUMO network, the vehicle controller and the local line-of-sight sensor read,
so the rays and the vehicles share one intersection. Plain Python, no Sionna;
the PLY/XML writers are the robot_ring scene's.
"""

from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[4]
sys.path.insert(0, str(REPO / "examples" / "v2x_intersection"))
sys.path.insert(0, str(HERE.parent / "robot_ring"))

import layout  # noqa: E402
from build_robot_ring import box, write_ply  # noqa: E402

SCENARIO_DIR = REPO / "examples" / "configs" / "sionna" / "scenarios" / "v2x_intersection"
MATERIALS = {"concrete": ("concrete", 0.2)}
ISO = {"rows": 1, "cols": 1, "pattern": "iso", "polarization": "V"}
SOLVER = {
    "max_depth": 3,
    "samples_per_source": 200000,
    "seed": 42,
    "path_polylines": 6,
    "propagation": {
        "los": True,
        "specular_reflection": True,
        "diffuse_reflection": False,
        "refraction": False,
        "diffraction": True,
    },
}


def ground():
    e = layout.GROUND_HALF_EXTENT_M
    return [[-e, -e, 0.0], [e, -e, 0.0], [e, e, 0.0], [-e, e, 0.0]], [[0, 1, 2], [0, 2, 3]]


def scenario(site: layout.RadioSite) -> dict:
    a_start = [layout.A_START_M[0], layout.A_START_M[1], layout.ANTENNA_HEIGHT_M]
    return {
        "name": f"v2x-intersection-{site.name}",
        "description": (
            f"V2X blind intersection ({site.description}). ue0 is vehicle A's UE: it waits at "
            "A's start position until examples/v2x_intersection/drive.py publishes live positions "
            "(--position-endpoint, scene frame, zero offset). ue1 is parked in line of sight of "
            "the gNB and carries no application traffic; the two-UE gate needs it. "
            "Generated by scenes/v2x_intersection/build_v2x_intersection.py from layout.py."
        ),
        "scene": "v2x_intersection",
        "simple_road": False,
        "solver": SOLVER,
        "nodes": {
            "gnb0": {"start_m": list(site.gnb_m), "mobility": "fixed", "array": ISO},
            "ue0": {"start_m": a_start, "mobility": "car", "array": ISO},
            "ue1": {"start_m": list(site.parked_ue_m), "mobility": "fixed", "array": ISO},
        },
        "links": [
            {"from": "gnb0", "to": "ue0", "direction": "downlink", "model": "sionna_rt"},
            {"from": "gnb0", "to": "ue1", "direction": "downlink", "model": "sionna_rt"},
            {"from": "ue0", "to": "gnb0", "direction": "uplink", "model": "sionna_rt"},
            {"from": "ue1", "to": "gnb0", "direction": "uplink", "model": "sionna_rt"},
        ],
    }


def main() -> int:
    meshes = HERE / "meshes"
    meshes.mkdir(exist_ok=True)
    shapes: list[tuple[str, str]] = []

    def emit(object_id: str, material: str, geometry) -> None:
        vertices, faces = geometry
        write_ply(meshes / f"{object_id}.ply", vertices, faces)
        shapes.append((object_id, material))

    emit("ground", "concrete", ground())
    for block in layout.BLOCKS:
        cx, cy = block.centre
        sx, sy = block.size
        emit(f"building_{block.name}", "concrete", box(cx, cy, sx, sy, 0.0, block.height_m))

    lines = ["<?xml version='1.0' encoding='utf-8'?>", '<scene version="2.1.0">']
    for material_id, (itu_type, thickness) in MATERIALS.items():
        lines += [
            f'  <bsdf type="itu-radio-material" id="{material_id}">',
            f'    <string name="type" value="{itu_type}" />',
            f'    <float name="thickness" value="{thickness}" />',
            "  </bsdf>",
        ]
    for object_id, material in shapes:
        lines += [
            f'  <shape type="ply" id="mesh-{object_id}">',
            f'    <string name="filename" value="meshes/{object_id}.ply" />',
            '    <boolean name="face_normals" value="true" />',
            f'    <ref id="{material}" name="bsdf" />',
            "  </shape>",
        ]
    lines.append("</scene>")
    (HERE / "scene.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")

    manifest = {
        "name": "v2x_intersection",
        "units": "Sionna XYZ metres, z up; intersection centre at the origin; equals the SUMO frame",
        "source": "examples/v2x_intersection/layout.py",
        "lane_width_m": layout.LANE_WIDTH_M,
        "conflict_point_m": list(layout.CONFLICT_POINT_M),
        "blocks": [{"id": f"building_{b.name}", "x_m": [b.x_min, b.x_max], "y_m": [b.y_min, b.y_max],
                    "height_m": b.height_m, "material": "concrete"} for b in layout.BLOCKS],
        "ground": {"half_extent_m": layout.GROUND_HALF_EXTENT_M, "material": "concrete"},
        "radio_sites": {name: {"gnb_m": list(s.gnb_m), "parked_ue_m": list(s.parked_ue_m),
                               "description": s.description} for name, s in layout.RADIO_SITES.items()},
        "shapes": [{"id": object_id, "material": material} for object_id, material in shapes],
    }
    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    SCENARIO_DIR.mkdir(parents=True, exist_ok=True)
    for site in layout.RADIO_SITES.values():
        path = SCENARIO_DIR / f"v2x-intersection-{site.name}.json"
        path.write_text(json.dumps(scenario(site), indent=2) + "\n", encoding="utf-8")
    print(f"wrote {HERE / 'scene.xml'} with {len(shapes)} shapes and "
          f"{len(layout.RADIO_SITES)} scenarios in {SCENARIO_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
