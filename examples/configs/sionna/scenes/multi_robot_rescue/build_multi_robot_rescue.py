#!/usr/bin/env python3
"""Generate the rescue building scene and its scenarios from layout.py.

    python3 build_multi_robot_rescue.py    # scene.xml + meshes/ + manifest.json here,
                                           # ../../scenarios/multi_robot_rescue/*.json

The geometry is `examples/multi_robot_rescue/layout.py`, the module the world
simulators, the referee and the dashboard also read, so the rays and the
robots share one building. Plain Python, no Sionna; the PLY writer is the
robot_ring scene's.

Walls and the roof are single sheets (a wall's centre plane, the roof's lower
plane): Sionna's ITU radio material models one surface as a slab of the
material's `thickness`, so a closed box would charge every wall twice — two
interactions and twice the slab loss per crossing. Rubble stays a closed box
(a blocker, crossed rarely).
"""

from __future__ import annotations

import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parents[4]
sys.path.insert(0, str(REPO / "examples" / "multi_robot_rescue"))
sys.path.insert(0, str(HERE.parent / "robot_ring"))

import layout  # noqa: E402
from build_robot_ring import write_ply  # noqa: E402

SCENARIO_DIR = REPO / "examples" / "configs" / "sionna" / "scenarios" / "multi_robot_rescue"
ISO = {"rows": 1, "cols": 1, "pattern": "iso", "polarization": "V"}
SOLVER = {
    "max_depth": 3,
    "samples_per_source": 200000,
    "seed": 42,
    "path_polylines": 6,
    "propagation": {
        "los": True,
        "specular_reflection": True,
        "diffuse_reflection": False,
        "refraction": True,          # walls are penetrable: through-wall paths carry the room coverage
        "diffraction": True,
    },
}
# Robots -> live UE count of the native multi-UE gate (it runs 2 or 4 UEs).
ROBOT_COUNTS = {1: 2, 2: 2, 3: 4}


def closed_box(b: layout.Box):
    xs, ys = (b.x0, b.x1, b.x1, b.x0), (b.y0, b.y0, b.y1, b.y1)
    vertices = [[x, y, b.z0] for x, y in zip(xs, ys)] + [[x, y, b.z1] for x, y in zip(xs, ys)]
    faces = []
    for i in range(4):
        j = (i + 1) % 4
        faces += [[i, j, 4 + j], [i, 4 + j, 4 + i]]
    faces += [[4, 5, 6], [4, 6, 7], [0, 2, 1], [0, 3, 2]]
    return vertices, faces


def wall_sheet(b: layout.Box):
    """Centre plane of a wall box along its long axis, from z0 to z1."""

    if b.x1 - b.x0 >= b.y1 - b.y0:
        y = (b.y0 + b.y1) / 2
        ring = [(b.x0, y), (b.x1, y)]
    else:
        x = (b.x0 + b.x1) / 2
        ring = [(x, b.y0), (x, b.y1)]
    (ax, ay), (bx, by) = ring
    vertices = [[ax, ay, b.z0], [bx, by, b.z0], [bx, by, b.z1], [ax, ay, b.z1]]
    return vertices, [[0, 1, 2], [0, 2, 3]]


def roof_sheet(b: layout.Box):
    vertices = [[b.x0, b.y0, b.z0], [b.x1, b.y0, b.z0], [b.x1, b.y1, b.z0], [b.x0, b.y1, b.z0]]
    return vertices, [[0, 2, 1], [0, 3, 2]]     # normal down, into the building


def ground():
    e = layout.GROUND_HALF_EXTENT_M
    cx, cy = layout.GROUND_CENTRE_M
    return [[cx - e, cy - e, 0.0], [cx + e, cy - e, 0.0], [cx + e, cy + e, 0.0], [cx - e, cy + e, 0.0]], \
        [[0, 1, 2], [0, 2, 3]]


def scenario(site: layout.RadioSite, robots: int) -> dict:
    ue_count = ROBOT_COUNTS[robots]
    nodes = {"gnb0": {"start_m": list(site.gnb_m), "mobility": "fixed", "array": ISO}}
    for index in range(ue_count):
        if index < robots:
            rid = layout.ROBOT_IDS[index]
            x, y, _ = layout.SPAWN_POSES[rid]
            nodes[f"ue{index}"] = {"start_m": [x, y, layout.ROBOT_ANTENNA_HEIGHT_M], "mobility": "robot",
                                   "array": ISO}
        else:
            px, py, pz = site.parked_ue_m
            nodes[f"ue{index}"] = {"start_m": [px, py - 2.0 * (index - robots), pz], "mobility": "fixed",
                                   "array": ISO}
    links = []
    for index in range(ue_count):
        links.append({"from": "gnb0", "to": f"ue{index}", "direction": "downlink", "model": "sionna_rt"})
        links.append({"from": f"ue{index}", "to": "gnb0", "direction": "uplink", "model": "sionna_rt"})
    robots_text = ", ".join(f"ue{i} = {layout.ROBOT_IDS[i]}" for i in range(robots))
    parked = ", ".join(f"ue{i}" for i in range(robots, ue_count))
    return {
        "name": f"multi-robot-rescue-{site.name}-{robots}robot",
        "description": (
            f"Multi-robot rescue building ({site.description}). {robots_text}: each waits at its robot's spawn "
            "until examples/multi_robot_rescue/sim.py publishes live positions (--position-endpoint, scene "
            "frame, zero offset)."
            + (f" {parked} parked outside in line of sight, no application traffic (the gate runs "
               f"{ue_count} UEs)." if parked else "")
            + " Generated by scenes/multi_robot_rescue/build_multi_robot_rescue.py from layout.py."),
        "scene": "multi_robot_rescue",
        "simple_road": False,
        "solver": SOLVER,
        "nodes": nodes,
        "links": links,
    }


def main() -> int:
    meshes = HERE / "meshes"
    meshes.mkdir(exist_ok=True)
    for old in meshes.glob("*.ply"):
        old.unlink()
    shapes: list[tuple[str, str]] = []

    def emit(object_id: str, material: str, geometry) -> None:
        vertices, faces = geometry
        write_ply(meshes / f"{object_id}.ply", vertices, faces)
        shapes.append((object_id, material))

    emit("ground", "concrete", ground())
    emit("roof", layout.ROOF.material, roof_sheet(layout.ROOF))
    for b in layout.WALLS:
        emit(b.name, b.material, wall_sheet(b))
    for b in layout.RUBBLE:
        emit(b.name, b.material, closed_box(b))

    used = sorted({material for _, material in shapes})
    lines = ["<?xml version='1.0' encoding='utf-8'?>", '<scene version="2.1.0">']
    for material_id in used:
        itu_type, thickness = layout.MATERIALS[material_id]
        lines += [
            f'  <bsdf type="itu-radio-material" id="{material_id}">',
            f'    <string name="type" value="{itu_type}" />',
            f'    <float name="thickness" value="{thickness}" />',
            "  </bsdf>",
        ]
    for object_id, material in shapes:
        lines += [
            f'  <shape type="ply" id="mesh-{object_id}">',
            f'    <string name="filename" value="meshes/{object_id}.ply" />',
            '    <boolean name="face_normals" value="true" />',
            f'    <ref id="{material}" name="bsdf" />',
            "  </shape>",
        ]
    lines.append("</scene>")
    (HERE / "scene.xml").write_text("\n".join(lines) + "\n", encoding="utf-8")

    manifest = {
        "name": "multi_robot_rescue",
        "units": "Sionna XYZ metres, z up; origin at the building's outer south-west corner; equals the site frame",
        "source": "examples/multi_robot_rescue/layout.py",
        "building_m": {"x": list(layout.BUILDING_X_M), "y": list(layout.BUILDING_Y_M),
                       "wall_height": layout.WALL_HEIGHT_M, "roof": [layout.ROOF.z0, layout.ROOF.z1]},
        "rooms": [{"name": r.name, "x_m": [r.x0, r.x1], "y_m": [r.y0, r.y1], "door_x_m": r.door_x} for r in layout.ROOMS],
        "shadow_room": layout.SHADOW_ROOM,
        "boxes": [{"id": b.name, "x_m": [b.x0, b.x1], "y_m": [b.y0, b.y1], "z_m": [b.z0, b.z1], "material": b.material}
                  for b in (layout.ROOF,) + layout.WALLS + layout.RUBBLE],
        "materials": {m: {"itu_type": layout.MATERIALS[m][0], "thickness_m": layout.MATERIALS[m][1]} for m in used},
        "radio_sites": {name: {"gnb_m": list(s.gnb_m), "parked_ue_m": list(s.parked_ue_m),
                               "description": s.description} for name, s in layout.RADIO_SITES.items()},
        "robot_spawns": {rid: list(p) for rid, p in layout.SPAWN_POSES.items()},
        "robot_antenna_height_m": layout.ROBOT_ANTENNA_HEIGHT_M,
        "shapes": [{"id": object_id, "material": material} for object_id, material in shapes],
    }
    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    SCENARIO_DIR.mkdir(parents=True, exist_ok=True)
    written = []
    for site in layout.RADIO_SITES.values():
        for robots in ROBOT_COUNTS:
            path = SCENARIO_DIR / f"multi-robot-rescue-{site.name}-{robots}robot.json"
            path.write_text(json.dumps(scenario(site, robots), indent=2) + "\n", encoding="utf-8")
            written.append(path.name)
    print(f"wrote {HERE / 'scene.xml'} with {len(shapes)} shapes; scenarios: {', '.join(written)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
